package com.arcam.viewfinder

/**
 * 人体姿势预设。
 *
 * 每个关节给三个数，单位都是「身高比例」：
 *   x  横向（右为正）
 *   y  离地高度
 *   z  前方（朝着相机为正）
 * 乘上身高就是米。站立那套就是原来的比例，其余姿势在它基础上改。
 *
 * 关节下标固定 18 个，顺序和 [ScenePainter] 里画线用的一致：
 *   0,1  脚底(左右)      2,3  脚踝      4,5  膝盖      6,7  髋
 *   8    腰              9    颈        10   下巴      11   头心
 *   12,13 肩            14,15 肘        16,17 手腕
 */
object Poses {

    data class J(val x: Double, val y: Double, val z: Double)

    private fun j(x: Double, y: Double, z: Double = 0.0) = J(x, y, z)

    /** 上半身整体下移，用来从站姿改坐姿/蹲姿 */
    private fun shiftDown(base: List<J>, d: Double): List<J> =
        base.mapIndexed { i, p -> if (i >= 8) p.copy(y = p.y - d) else p }

    val STAND = listOf(
        j(-0.048, 0.000), j(0.048, 0.000),        // 0,1 脚底
        j(-0.048, 0.045), j(0.048, 0.045),        // 2,3 脚踝
        j(-0.043, 0.280), j(0.043, 0.280),        // 4,5 膝
        j(-0.072, 0.530), j(0.072, 0.530),        // 6,7 髋
        j(0.000, 0.610),                          // 8 腰
        j(0.000, 0.855),                          // 9 颈
        j(0.000, 0.867),                          // 10 下巴
        j(0.000, 0.9335),                         // 11 头心
        j(-0.105, 0.800), j(0.105, 0.800),        // 12,13 肩
        j(-0.124, 0.635), j(0.124, 0.635),        // 14,15 肘
        j(-0.137, 0.445), j(0.137, 0.445),        // 16,17 手腕
    )

    /** 坐椅子：髋落到 0.45m 左右，大腿前伸，上半身整体下移 */
    val SIT = shiftDown(STAND, 0.257).let { b ->
        b.toMutableList().apply {
            this[0] = j(-0.048, 0.000, 0.270); this[1] = j(0.048, 0.000, 0.270)
            this[2] = j(-0.043, 0.048, 0.245); this[3] = j(0.043, 0.048, 0.245)
            this[4] = j(-0.043, 0.275, 0.245); this[5] = j(0.043, 0.275, 0.245)
            this[6] = j(-0.072, 0.273, 0.010); this[7] = j(0.072, 0.273, 0.010)
            this[8] = j(0.000, 0.353, -0.010)
            this[9] = j(0.000, 0.598, -0.025)
            this[10] = j(0.000, 0.610, -0.025)
            this[11] = j(0.000, 0.6765, -0.025)
            this[12] = j(-0.105, 0.543, -0.025); this[13] = j(0.105, 0.543, -0.025)
            this[14] = j(-0.124, 0.378, 0.010); this[15] = j(0.124, 0.378, 0.010)
            this[16] = j(-0.137, 0.188, 0.060); this[17] = j(0.137, 0.188, 0.060)
        }
    }

    /** 走路：两腿前后错开，手臂反向摆 */
    val WALK = STAND.toMutableList().apply {
        this[0] = j(-0.048, 0.000, 0.160); this[1] = j(0.048, 0.000, -0.160)
        this[2] = j(-0.048, 0.045, 0.150); this[3] = j(0.048, 0.048, -0.140)
        this[4] = j(-0.045, 0.280, 0.090); this[5] = j(0.045, 0.275, -0.110)
        this[14] = j(-0.124, 0.635, -0.050); this[16] = j(-0.137, 0.445, -0.110)
        this[15] = j(0.124, 0.635, 0.050); this[17] = j(0.137, 0.445, 0.110)
    }

    /**
     * 靠墙：肩背贴墙（墙在身后，z 取负），骨盆前顶，一腿伸直、一腿屈起踩墙
     * 两只手都插兜，重心压在直腿上
     */
    val LEAN = STAND.toMutableList().apply {
        this[0] = j(-0.052, 0.000, -0.230); this[1] = j(0.052, 0.000, 0.030)   // 左腿伸直踩地，右腿屈起
        this[2] = j(-0.052, 0.045, -0.225); this[3] = j(0.052, 0.330, 0.075)   // 右脚踩在墙上（抬高）
        this[4] = j(-0.048, 0.280, -0.190); this[5] = j(0.062, 0.360, 0.140)
        this[6] = j(-0.072, 0.530, -0.075); this[7] = j(0.072, 0.530, -0.075)
        this[8] = j(0.000, 0.610, -0.110)
        this[9] = j(0.000, 0.855, -0.140)
        this[10] = j(0.000, 0.867, -0.140)
        this[11] = j(0.000, 0.9335, -0.135)
        this[12] = j(-0.105, 0.800, -0.140); this[13] = j(0.105, 0.800, -0.140)
        this[14] = j(-0.122, 0.640, -0.115); this[15] = j(0.122, 0.640, -0.115)
        this[16] = j(-0.090, 0.560, -0.060); this[17] = j(0.090, 0.560, -0.060)   // 手插兜
    }

    /** 沉思：头略低，右手抵下巴，左臂横过来托着右肘 */
    val THINK = STAND.toMutableList().apply {
        this[9] = j(0.000, 0.850, 0.005)
        this[10] = j(0.005, 0.858, 0.015)
        this[11] = j(0.008, 0.920, 0.020)
        this[14] = j(-0.118, 0.618, 0.020); this[16] = j(0.028, 0.560, 0.075)
        this[15] = j(0.126, 0.605, 0.015); this[17] = j(0.060, 0.808, 0.060)
    }

    /** 抱胸：两臂在胸前交叠 */
    val ARMS_CROSSED = STAND.toMutableList().apply {
        this[14] = j(-0.126, 0.622, 0.030); this[16] = j(0.072, 0.672, 0.095)
        this[15] = j(0.126, 0.622, 0.030); this[17] = j(-0.072, 0.652, 0.105)
    }

    /** 名字 → 关节表。面板按钮按这个顺序排 */
    val ALL: List<Pair<String, List<J>>> = listOf(
        "站" to STAND,
        "走" to WALK,
        "坐" to SIT,
        "靠墙" to LEAN,
        "沉思" to THINK,
        "抱胸" to ARMS_CROSSED,
    )

    /** 画线用的骨骼段：每两个一组是关节下标 */
    val BONES = intArrayOf(
        6, 7, 12, 13, 8, 9,           // 髋、肩、脊柱
        6, 4, 4, 2, 2, 0,             // 左腿
        7, 5, 5, 3, 3, 1,             // 右腿
        12, 14, 14, 16,               // 左臂
        13, 15, 15, 17,               // 右臂
        9, 10,                        // 颈—下巴
    )

    /** 每段的线宽（相对值，乘 ScenePainter 的 unit） */
    val BONE_W = floatArrayOf(
        7f, 7f, 9f,
        9f, 7f, 5f,
        9f, 7f, 5f,
        7f, 6f,
        7f, 6f,
        6f,
    )

    /** 躯干段画亮一点，四肢淡一点 */
    val BONE_MAIN = booleanArrayOf(
        true, true, true,
        false, false, false,
        false, false, false,
        false, false,
        false, false,
        true,
    )
}
